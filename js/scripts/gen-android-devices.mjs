const out = header + JSON.stringify(picked, null, 2) + ' as const\n'
const dest = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'engine', 'android-devices.ts')
fs.writeFileSync(dest, out, 'utf8')
console.log(`wrote ${dest} (${picked.length} devices, ${out.length} bytes)`)
