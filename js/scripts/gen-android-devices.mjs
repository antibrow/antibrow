/**
 * Regenerate src/engine/android-devices.ts from the device corpus.
 *
 * The free tier ships three Android devices in-package so an Android profile
 * can be created offline. They are picked for spread: two GPU families and
 * three screen sizes.
 *
 * Run: node scripts/gen-android-devices.mjs <path-to>/real-devices.json
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const MODELS = ['SM-S918U', 'moto g05', 'SM-S936U']

const src = process.argv[2]
if (!src) {
  console.error('usage: node scripts/gen-android-devices.mjs <real-devices.json>')
  process.exit(1)
}

const corpus = JSON.parse(fs.readFileSync(src, 'utf8'))
const picked = MODELS.map((model) => {
  const row = corpus.devices.find((d) => d.os === 'android' && d.model === model)
  if (!row) throw new Error(`corpus is missing ${model}`)
  const { weight, ...device } = row
  return device
})

const header = `// Generated by scripts/gen-android-devices.mjs - do not edit by hand.
//
// Three real Android devices shipped in-package so the free tier can create an
// Android profile with no network round-trip. Each entry is one machine's bound
// set of facts: the screen, the GPU report and the UA client hints only agree
// with each other because they came off the same device, so pick a whole row,
// never a field.

import type { RealDevice } from './devices'

export const ANDROID_FALLBACK_DEVICES: readonly RealDevice[] = `

const out = header + JSON.stringify(picked, null, 2) + ' as const\n'
const dest = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'engine', 'android-devices.ts')
fs.writeFileSync(dest, out, 'utf8')
console.log(`wrote ${dest} (${picked.length} devices, ${out.length} bytes)`)
